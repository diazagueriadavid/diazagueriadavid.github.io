// Esta función se ejecuta una sola vez al comenzar.
function setup() {

    // Creamos un lienzo de 400 x 400 píxeles.
    createCanvas(600, 400);

    // Pintamos el fondo de color gris claro.
    background(255);

    // Dibujamos una línea horizontal.
    line(50, 50, 350, 50);

    // Dibujamos un círculo en el centro.
    circle(200, 200, 150);

    // Dibujamos un rectángulo.
    rect(50, 280, 100, 60);
}

